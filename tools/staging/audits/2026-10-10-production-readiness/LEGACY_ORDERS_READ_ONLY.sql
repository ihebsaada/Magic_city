\set ON_ERROR_STOP on
\pset pager off
BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY;
SET LOCAL statement_timeout = '30s';
SELECT 1 / CASE WHEN current_database() = 'magiccitydb_3334' THEN 1 ELSE 0 END AS production_database_guard;
SELECT current_database() AS database, current_setting('server_version') AS server_version,
       current_setting('transaction_read_only') AS read_only;

-- Presence is not inferred from migration history. Absent optional tables are UNKNOWN, not empty.
SELECT name, to_regclass(format('public.%I',name)) IS NOT NULL AS present
FROM (VALUES ('Order'),('OrderItem'),('PaymentAttempt'),('PaymentFinalization'),('StripeEvent'),
 ('GuestOrderAccess'),('GuestOrderRecovery'),('OrderReservation'),('StockReservationItem'),
 ('OrderHandoff'),('NavigationHandoff'),('_prisma_migrations')) AS expected(name);
SELECT table_name,column_name,data_type FROM information_schema.columns
WHERE table_schema='public' AND table_name IN ('Order','PaymentAttempt','GuestOrderAccess','OrderReservation','StockReservationItem')
ORDER BY table_name,ordinal_position;

-- psql gexec executes ONLY SELECT statements generated by these fixed templates.
-- to_jsonb tolerates missing historical columns; inventory below must identify missing fields as drift.
SELECT CASE WHEN to_regclass('public."Order"') IS NULL THEN 'SELECT ''BLOCKED: Order table missing'' AS audit;'
ELSE $q$SELECT count(*) AS total_orders,
 count(*) FILTER (WHERE (to_jsonb(o)->>'orderNumber') ~ '^[0-9]+$' AND (to_jsonb(o)->>'orderNumber')::numeric BETWEEN 1 AND 12) AS records_numbered_1_to_12,
 count(*) FILTER (WHERE to_jsonb(o)->>'orderNumber' IS NULL) AS missing_order_number
 FROM public."Order" o;$q$ END
\gexec
SELECT $q$SELECT to_jsonb(o)->>'paymentStatus' AS payment_status,to_jsonb(o)->>'status' AS order_status,
 to_jsonb(o)->>'currency' AS currency,count(*) AS orders FROM public."Order" o GROUP BY 1,2,3 ORDER BY 1,2,3;$q$
WHERE to_regclass('public."Order"') IS NOT NULL
\gexec
SELECT $q$WITH visible AS (SELECT generate_series(1,12)::text AS number)
SELECT v.number AS admin_reported_number,count(o.*) AS database_matches
FROM visible v LEFT JOIN public."Order" o ON to_jsonb(o)->>'orderNumber'=v.number
GROUP BY v.number ORDER BY v.number::integer;$q$
WHERE to_regclass('public."Order"') IS NOT NULL
\gexec
SELECT $q$SELECT to_jsonb(o)->>'orderNumber' AS number,to_jsonb(o)->>'paymentStatus' AS payment_status,
 to_jsonb(o)->>'status' AS status,to_jsonb(o)->>'currency' AS currency,to_jsonb(o)->>'total' AS frozen_total,
 CASE WHEN nullif(to_jsonb(o)->>'stripeSessionId','') IS NULL THEN 'NONE'
 WHEN to_jsonb(o)->>'stripeSessionId' ~ '^cs_test_' THEN 'TEST_PREFIX_HINT'
 WHEN to_jsonb(o)->>'stripeSessionId' ~ '^cs_live_' THEN 'LIVE_PREFIX_REQUIRES_STRIPE_VERIFICATION'
 ELSE 'UNKNOWN_REFERENCE_FORMAT' END AS stripe_reference_hint,
 nullif(to_jsonb(o)->>'sumupCheckoutId','') IS NOT NULL AS has_sumup_checkout,
 nullif(to_jsonb(o)->>'sumupPaymentId','') IS NOT NULL AS has_sumup_payment
FROM public."Order" o ORDER BY to_jsonb(o)->>'orderNumber';$q$
WHERE to_regclass('public."Order"') IS NOT NULL
\gexec

-- Count each dependency, including orphan references. No token/hash/request/PII exported.
SELECT format($q$SELECT %L AS dependency,count(*) AS rows,
 count(*) FILTER (WHERE d.j->>'orderId' IS NOT NULL) AS bound_rows,
 count(*) FILTER (WHERE d.j->>'orderId' IS NOT NULL AND o.id IS NULL) AS orphan_order_references
 FROM (SELECT to_jsonb(t) AS j FROM public.%I t) d
 LEFT JOIN public."Order" o ON o.id=d.j->>'orderId';$q$,name,name)
FROM (VALUES ('OrderItem'),('PaymentAttempt'),('PaymentFinalization'),('GuestOrderAccess'),('GuestOrderRecovery'),('OrderReservation'),('StockReservationItem'),('NavigationHandoff')) AS deps(name)
WHERE to_regclass(format('public.%I',name)) IS NOT NULL AND to_regclass('public."Order"') IS NOT NULL
\gexec
SELECT format($q$SELECT o."orderNumber" AS number,%L AS dependency,count(t.*) AS rows
 FROM public."Order" o LEFT JOIN public.%I t ON to_jsonb(t)->>'orderId'=o.id
 GROUP BY o.id,o."orderNumber" ORDER BY o."orderNumber";$q$,name,name)
FROM (VALUES ('PaymentAttempt'),('PaymentFinalization'),('GuestOrderAccess'),('OrderReservation'),('StockReservationItem')) AS deps(name)
WHERE to_regclass(format('public.%I',name)) IS NOT NULL AND to_regclass('public."Order"') IS NOT NULL
\gexec
SELECT $q$SELECT "state",count(*) AS attempts,
 count(*) FILTER(WHERE "sessionId" ~ '^cs_test_') AS test_prefix_hints,
 count(*) FILTER(WHERE "sessionId" ~ '^cs_live_') AS live_prefix_hints,
 count(*) FILTER(WHERE "sessionId" IS NULL) AS no_session_reference
 FROM public."PaymentAttempt" GROUP BY "state" ORDER BY "state";$q$
WHERE to_regclass('public."PaymentAttempt"') IS NOT NULL
\gexec
SELECT $q$SELECT count(*) AS grants,
 count(*) FILTER(WHERE "orderId" IS NOT NULL AND "revokedAt" IS NULL AND "expiresAt">transaction_timestamp()) AS active_bound_grants,
 count(*) FILTER(WHERE "orderId" IS NULL) AS unbound_prepared_grants
 FROM public."GuestOrderAccess";$q$
WHERE to_regclass('public."GuestOrderAccess"') IS NOT NULL
\gexec
SELECT $q$SELECT "state",count(*) AS reservations,
 count(*) FILTER(WHERE "expiresAt">transaction_timestamp()) AS not_expired_by_timestamp
 FROM public."OrderReservation" GROUP BY "state" ORDER BY "state";$q$
WHERE to_regclass('public."OrderReservation"') IS NOT NULL
\gexec
SELECT $q$SELECT count(*) AS orphan_stock_reservation_links FROM public."StockReservationItem" i
 LEFT JOIN public."OrderReservation" r ON r."orderId"=i."orderId" WHERE r."orderId" IS NULL;$q$
WHERE to_regclass('public."StockReservationItem"') IS NOT NULL AND to_regclass('public."OrderReservation"') IS NOT NULL
\gexec
SELECT $q$SELECT count(*) AS order_attempt_session_disagreements FROM public."PaymentAttempt" a
 JOIN public."Order" o ON o.id=a."orderId"
 WHERE a."sessionId" IS NOT NULL AND o."stripeSessionId" IS NOT NULL AND a."sessionId"<>o."stripeSessionId";$q$
WHERE to_regclass('public."PaymentAttempt"') IS NOT NULL
\gexec
-- Multiple generations can legitimately differ: disagreement is review evidence, not automatic corruption.
SELECT $q$SELECT migration_name,checksum,finished_at IS NOT NULL AS finished,
 rolled_back_at IS NOT NULL AS rolled_back FROM public._prisma_migrations ORDER BY migration_name;$q$
WHERE to_regclass('public._prisma_migrations') IS NOT NULL
\gexec
ROLLBACK;
